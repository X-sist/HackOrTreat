"""Generate language constants and consumer pins from the shared contract.

Only integration PRs edit these outputs. --check never writes.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def outputs(root=ROOT):
    source = root / 'shared/contract.json'
    contract = json.loads(source.read_text(encoding='utf-8'))
    # Digest semantic JSON, independent of Windows line endings or indentation.
    canonical = json.dumps(contract, sort_keys=True, separators=(',', ':')).encode()
    digest = hashlib.sha256(canonical).hexdigest()
    blob = json.dumps(contract, indent=2)
    result = {
        'shared/generated/protocol.py': '# Generated by tools/generate_contract.py; do not edit.\nimport json\nfrom types import MappingProxyType\ndef _freeze(value):\n    if isinstance(value, dict):\n        return MappingProxyType({key: _freeze(item) for key, item in value.items()})\n    if isinstance(value, list):\n        return tuple(_freeze(item) for item in value)\n    return value\nCONTRACT = _freeze(json.loads(' + repr(blob) + '))\n',
        'shared/generated/protocol.mjs': '// Generated; do not edit.\nfunction freeze(v) { if (v && typeof v === "object") { Object.values(v).forEach(freeze); Object.freeze(v); } return v; }\nexport const CONTRACT = freeze(' + blob + ');\n',
    }
    header = ['// Generated; do not edit.', '#pragma once', '#include <stdint.h>', 'namespace HackOrTreat {']
    for key, value in contract['constants'].items():
        if type(value) is bool:
            header.append(f'constexpr bool {key} = {str(value).lower()};')
        else:
            if type(value) is not int or not 0 <= value <= 0xFFFFFFFF:
                raise ValueError(f'invalid C++ constant {key}')
            header.append(f'constexpr uint32_t {key} = {value}UL;')
    header.append('}')
    for name in contract['event_fields']:
        header.append(f'#define HACKORTREAT_EVENT_{name.upper()} "{name}"')
    codes = set(contract['error_codes']) | set(contract['protocol_error_codes']) | set(contract['disturbance_reasons'])
    for name in sorted(codes):
        header.append(f'#define HACKORTREAT_CODE_{name} "{name}"')
    for name in sorted({reason for values in contract['disturbance_reasons'].values() for reason in values}):
        header.append(f'#define HACKORTREAT_REASON_{name} "{name}"')
    result['shared/generated/protocol.h'] = '\n'.join(header) + '\n'
    pin = json.dumps({'contract_revision': contract['revision'], 'wire_version': contract['constants']['PROTOCOL_VERSION'], 'contract_sha256': digest}, indent=2) + '\n'
    for component in ('firmware', 'sender', 'receiver'):
        result[f'{component}/contract.lock.json'] = pin
    result['shared/contract.lock.json'] = pin
    return result

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    changed = []
    for name, expected in outputs().items():
        target = ROOT / name
        actual = target.read_text(encoding='utf-8') if target.exists() else None
        if actual != expected:
            changed.append(name)
            if not args.check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(expected, encoding='utf-8', newline='\n')
    if changed and args.check:
        raise SystemExit('STALE shared contract/consumer pins: ' + ', '.join(changed))
    print('Contract outputs match' if args.check else f'Generated/refreshed {len(changed)} outputs')

if __name__ == '__main__':
    main()
